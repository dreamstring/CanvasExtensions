'use strict';
const assert = require('node:assert/strict');
const { create } = require('../runtime/ui-model.js');
const state = { manual: false, scale: 100 };
let commits = 0;
const model = create(state, { onChange: () => commits++ });
const percent = model.derive(state => state.scale + '%');
const changes = [];
const resources = [];
const stop = model.subscribe(s => s.manual ? s.scale : 0, (next, previous, onCleanup) => {
  changes.push([next, previous]);
  const controller = new AbortController();
  resources.push(controller);
  onCleanup(() => controller.abort());
}, { immediate: true });
assert.equal(model.patch({ scale: 50 }), true);
assert.equal(percent.value, '50%');
assert.equal(changes.length, 1);
assert.equal(model.patch({ manual: true, scale: 75 }), true);
assert.deepEqual(changes, [[0, undefined], [75, 0]]);
assert.equal(resources[0].signal.aborted, true);
assert.equal(model.patch({ scale: 75 }), false);
assert.equal(resources[1].signal.aborted, false);
stop();
stop();
assert.equal(resources[1].signal.aborted, true);
const seen = [];
model.subscribe(s => s.scale, next => { if (next === 10) model.patch({ scale: 20 }); });
model.subscribe(s => s.scale, next => seen.push(next));
const priorCommits = commits;
model.patch({ scale: 10 });
assert.equal(commits, priorCommits + 1);
assert.equal(seen.at(-1), 20);
let cleaned = 0;
model.subscribe(s => s.scale, (_, __, clean) => clean(() => cleaned++), { immediate: true });
model.dispose();
model.dispose();
assert.equal(cleaned, 1);
assert.equal(model.patch({ scale: 44 }), false);
assert.equal(state.scale, 20);
assert.throws(() => model.subscribe(() => 1, () => {}), /disposed/);
const nested = create({ value: 1 });
const ended = [];
nested.subscribe(s => s.value, (next, previous, onCleanup) => {
  if (next === 1) nested.patch({ value: 2 });
  onCleanup(() => ended.push(next));
}, { immediate: true });
assert.deepEqual(ended, [1]);
nested.dispose();
assert.deepEqual(ended, [1, 2]);
console.log('PASS UI model: derived values, atomic patches, selected subscriptions, cancellation and disposal');
let saves = 0;
const preset = create({ name: 'balanced', left: 20 }, { onChange: () => saves++ });
const snapshots = [];
preset.subscribe(s => s.name + '/' + s.left, next => snapshots.push(next));
preset.batch(() => {
  preset.patch({ name: 'asymmetric' });
  preset.batch(() => preset.patch({ left: 12 }));
});
assert.deepEqual(snapshots, ['asymmetric/12']);
assert.equal(saves, 1);
assert.throws(() => preset.batch(() => {
  preset.patch({ left: 10 });
  throw Error('incomplete callback');
}), /incomplete callback/);
assert.equal(saves, 2);
preset.patch({ left: 15 });
assert.equal(saves, 3);
const dimensions = create({ left: 10, right: 20, enabled: true });
const edges = [];
const unwatch = dimensions.watchKeys(['left', 'right'], (next, previous) => edges.push([next, previous]), { immediate: true });
dimensions.patch({ enabled: false });
dimensions.batch(() => {
  dimensions.patch({ left: 5 });
  dimensions.patch({ right: 25 });
});
unwatch();
dimensions.patch({ left: 0 });
assert.deepEqual(edges, [[[10, 20], undefined], [[5, 25], [10, 20]]]);
